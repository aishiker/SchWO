class ShardRunError(RuntimeError):
    """Raised after a shard has published a durable fail-closed root."""


def _fsync_directory(path: Path) -> None:
    descriptor = os.open(path, os.O_RDONLY)
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def _publish_json_exclusive(path: Path, payload: object) -> dict[str, object]:
    """Publish complete canonical JSON atomically without replacing a path."""

    if path.exists() or path.is_symlink():
        raise FileExistsError(f"output collision: {path}")
    data = canonical_json_bytes(payload)
    staging = path.with_name(
        f".{path.name}.o_excl_staging_{os.getpid()}_{time.time_ns()}"
    )
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW
    descriptor = os.open(staging, flags, 0o600)
    linked = False
    try:
        with os.fdopen(descriptor, "wb", closefd=True) as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(staging, 0o444)
        _fsync_directory(path.parent)
        os.link(staging, path, follow_symlinks=False)
        linked = True
        _fsync_directory(path.parent)
    except Exception:
        try:
            os.close(descriptor)
        except OSError:
            pass
        raise
    finally:
        try:
            staging.unlink()
        except FileNotFoundError:
            pass
        _fsync_directory(path.parent)
    if not linked:
        raise RuntimeError("exclusive JSON publication did not create a final link")
    identity = source_file_identity(path)
    if identity["mode"] != 0o444 or identity["sha256"] != sha256_bytes(data):
        raise RuntimeError("exclusive JSON publication identity mismatch")
    return identity


def _strict_json(path: Path) -> dict[str, object]:
    if path.is_symlink() or not path.is_file():
        raise ShardRunError(f"JSON artifact is missing or aliased: {path}")
    raw = path.read_bytes()
    try:
        value = json.loads(raw)
    except json.JSONDecodeError as exc:
        raise ShardRunError(f"JSON artifact is malformed: {path}") from exc
    if not isinstance(value, dict) or raw != canonical_json_bytes(value):
        raise ShardRunError(f"JSON artifact is not a canonical object: {path}")
    return value


def _validate_identity(
    identity: object,
    *,
    path: Path,
) -> dict[str, object]:
    if not isinstance(identity, Mapping) or set(identity) != {
        "mode",
        "nlink",
        "path",
        "sha256",
        "size",
    }:
        raise ShardRunError("artifact identity schema changed")
    actual = source_file_identity(path)
    if actual["mode"] != 0o444 or actual != dict(identity):
        raise ShardRunError(f"artifact identity changed: {path}")
    return actual


