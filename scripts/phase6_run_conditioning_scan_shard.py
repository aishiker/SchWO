def _build_run_contract(
    *,
    frozen: FrozenScanContract,
    shard_id: str,
    output_root: Path,
    resume_from: Path | None,
    policy: ConditioningPolicy,
    selector: Selector,
    test_mode: bool,
    selector_injected: bool,
    solver_injected: bool,
) -> tuple[dict[str, object], dict[RadialKey, OuterSelection]]:
    shard = dict(frozen.shard_record(shard_id))
    keys = frozen.shard_keys(shard_id)
    union_ordinals = {key: index for index, key in enumerate(frozen.union_keys)}
    plans: list[dict[str, object]] = []
    selections: dict[RadialKey, OuterSelection] = {}
    for shard_ordinal, key in enumerate(keys):
        selection = selector(key)
        if selection.key != key:
            raise ShardRunError("selector returned a foreign key")
        selections[key] = selection
        transition_key = key in frozen.transition_keys
        nodes = calibration_solve_nodes(
            selection,
            transition_key=transition_key,
            policy=policy,
        )
        if selection.supported:
            descriptors = [node.descriptor() for node in nodes]
        else:
            descriptors = [
                {
                    "actual_precision_digits": 16,
                    "node_id": "baseline_preflight",
                    "tolerance": policy.baseline_rtol,
                }
            ]
        plans.append(
            {
                "domain_ordinal": union_ordinals[key],
                "key": key.to_record(),
                "ladder_axis_descriptors": descriptors,
                "ladder_axis_map_sha256": sha256_bytes(
                    canonical_json_bytes(descriptors)
                ),
                "outer_selection": selection.to_record(),
                "shard_ordinal": shard_ordinal,
                "solve_nodes": [node.to_record() for node in nodes],
                "transition_key": transition_key,
            }
        )
    sources = _source_identities()
    domain_hashes = {
        f"domain:{name}": identity["sha256"]
        for name, identity in sorted(frozen.domain_identities.items())
    }
    execution_hashes = {
        f"execution:{name}": identity["sha256"]
        for name, identity in sorted(frozen.execution_identities.items())
    }
    implementation_hashes = {
        f"source:{name}": digest for name, digest in source_hash_map(sources).items()
    }
    source_hashes = {**domain_hashes, **execution_hashes, **implementation_hashes}
    record: dict[str, object] = {
        "actual_precision": {
            "backend": "scipy_float64_conditioned_radial_v1",
            "digits": 16,
        },
        "backend_hashes": {
            "conditioned_backend": sources["conditioned_backend"]["sha256"],
            "matching": sources["matching"]["sha256"],
            "potentials": sources["potentials"]["sha256"],
        },
        "code_hashes": {
            "scan_module": sources["scan_module"]["sha256"],
            "shard_runner": sources["shard_runner"]["sha256"],
        },
        "config_hashes": {"conditioning_policy": policy.sha256},
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "domain_contract_sha256": frozen.domain_identities["domain_contract.json"][
            "sha256"
        ],
        "domain_union_key_list_sha256": frozen.domain_identities["D_union.jsonl"][
            "sha256"
        ],
        "execution_contract_sha256": frozen.execution_identities[
            "execution_contract.json"
        ]["sha256"],
        "execution_manifest_sha256": frozen.execution_identities["manifest.json"][
            "sha256"
        ],
        "execution_mode": {
            "scientific_use_permitted": not test_mode,
            "selector_injected": selector_injected,
            "solver_injected": solver_injected,
            "status": (
                "TEST_ONLY_FAKE_INJECTION_NO_SCIENTIFIC_USE"
                if test_mode
                else "PRODUCTION_GENERIC_CONDITIONED_BACKEND"
            ),
        },
        "global_green_permitted": False,
        "key_plans": plans,
        "observable_definitions": {
            "flux_residual": "abs(|A_out|^2 + |T_horizon|^2 - 1)",
            "normalization": "A_in=1 at infinity",
            "production_finite_radius_states": "NOT_ASSESSED",
            "radial_s_matrix": "S_ell=-A_out/(-1)^ell",
            "required_radius_state": f"Schwarzschild radius r/M={policy.required_radius_M:.17g}",
        },
        "output_root": str(output_root),
        "paper_figure_runs": 0,
        "policy": policy.to_record(),
        "policy_sha256": policy.sha256,
        "resume_from": None if resume_from is None else str(resume_from),
        "runtime_identity": _runtime_identity(),
        "schema": RUN_CONTRACT_SCHEMA,
        "shard": shard,
        "shard_keys": [key.to_record() for key in keys],
        "source_hashes": source_hashes,
        "source_identities": sources,
        "status": "FROZEN_SHARD_PLAN_NO_ACCEPTANCE_CLAIM",
        "transition_contract_sha256": frozen.execution_identities[
            "D_transition_calibration.jsonl"
        ]["sha256"],
    }
    record["context_sha256"] = scan_context_hash(record)
    return record, selections


