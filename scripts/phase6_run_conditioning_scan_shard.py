def _publish_key_artifacts(
    *,
    output_root: Path,
    contract: Mapping[str, object],
    plan: Mapping[str, object],
    key: RadialKey,
    solver_payload: Mapping[str, object],
) -> dict[str, object]:
    filenames = key_artifact_filenames(int(plan["shard_ordinal"]), key)
    payload_envelope = {
        "domain_contract_sha256": contract["domain_contract_sha256"],
        "domain_union_key_list_sha256": contract["domain_union_key_list_sha256"],
        "execution_contract_sha256": contract["execution_contract_sha256"],
        "execution_manifest_sha256": contract["execution_manifest_sha256"],
        "key": key.to_record(),
        "schema": KEY_PAYLOAD_ENVELOPE_SCHEMA,
        "shard": contract["shard"],
        "solver_payload": dict(solver_payload),
        "solver_payload_schema": SOLVER_PAYLOAD_SCHEMA,
    }
    payload_identity = _publish_json_exclusive(
        output_root / filenames["payload"], payload_envelope
    )
    checkpoint = _checkpoint_base(contract=contract, solver_payload=solver_payload)
    checkpoint["result_identity"] = {
        "mode": 0o444,
        "nlink": 1,
        "path": "pending",
        "sha256": "0" * 64,
        "size": 1,
    }
    result = {
        "acceptance_state": checkpoint["acceptance_state"],
        "actual_precision": checkpoint["actual_precision"],
        "domain_contract_sha256": checkpoint["domain_contract_sha256"],
        "domain_union_key_list_sha256": checkpoint["domain_union_key_list_sha256"],
        "execution_contract_sha256": checkpoint["execution_contract_sha256"],
        "execution_manifest_sha256": checkpoint["execution_manifest_sha256"],
        "key": checkpoint["key"],
        "observable_statuses": checkpoint["observable_statuses"],
        "payload_identity": payload_identity,
        "payload_schema": KEY_PAYLOAD_ENVELOPE_SCHEMA,
        "resume_claims_sha256": resume_claims_sha256(checkpoint),
        "schema": KEY_RESULT_SCHEMA,
        "shard": checkpoint["shard"],
    }
    result_identity = _publish_json_exclusive(output_root / filenames["result"], result)
    checkpoint["result_identity"] = result_identity
    checkpoint_identity = _publish_json_exclusive(
        output_root / filenames["checkpoint"], checkpoint
    )
    status = (
        "COMPLETED"
        if solver_payload["acceptance_state"] != "FAIL"
        else "COMPLETED_FAIL_CLOSED"
    )
    terminal = {
        "checkpoint_identity": checkpoint_identity,
        "domain_ordinal": plan["domain_ordinal"],
        "execution_status": status,
        "failure": None,
        "global_green_permitted": False,
        "key": key.to_record(),
        "predecessor": None,
        "schema": KEY_TERMINAL_SCHEMA,
        "shard_ordinal": plan["shard_ordinal"],
        "solver_call_count_this_run": solver_payload["total_solver_call_count"],
    }
    terminal_identity = _publish_json_exclusive(
        output_root / filenames["terminal"], terminal
    )
    return {
        "checkpoint": checkpoint,
        "checkpoint_identity": checkpoint_identity,
        "result_identity": result_identity,
        "terminal": terminal,
        "terminal_identity": terminal_identity,
    }


